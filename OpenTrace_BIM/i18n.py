# OpenTrace 0.12.9: English-only UI with explicit, local translation.
#
# IngeTrazo discovers third-party extensions by file path, independently of the
# host translation catalog.  Older OpenTrace builds relied on the host locale
# plus a partial extension dictionary, which could leave newer controls in
